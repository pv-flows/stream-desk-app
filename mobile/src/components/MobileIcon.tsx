export const MobileIcon: React.FC<MobileIconProps> = ({
  iconName,
  size = 24,
  color = '#ffffff',
  iconStyle = 'linha',
}) => {
  const isFilled = iconStyle === 'preenchido';
  const strokeWidth = isFilled ? 2.8 : 1.8;

  if (!iconName) {
    return <Zap size={size} color={color} fill={isFilled ? color : 'none'} strokeWidth={strokeWidth} />;
  }

  // Se for ícone base64 extraído do Windows
  if (iconName.startsWith('base64:') || iconName.startsWith('data:image')) {
    const uri = iconName.startsWith('base64:')
      ? `data:image/png;base64,${iconName.slice(7)}`
      : iconName;
    return (
      <Image
        source={{ uri }}
        style={[styles.base64Image, { width: size, height: size }]}
        resizeMode="contain"
      />
    );
  }

  const raw = iconName.toLowerCase().trim();
  const sanitized = raw.replace(/[-_\s]/g, '');
  const IconComponent = ICON_MAP[raw] || ICON_MAP[sanitized] || Zap;

  return <IconComponent size={size} color={color} fill={isFilled ? color : 'none'} strokeWidth={strokeWidth} />;
};

const styles = StyleSheet.create({
  base64Image: {
    borderRadius: 4,
  },
});
